// Writes src/environments/environment.production.ts from environment variables, so the public addresses are set in
// the hosting dashboard instead of being edited in code. Run automatically by `npm run build`.
//
//   PUBLIC_API_URL      the API address the browser calls, e.g. https://api.example.com/api   (required on Render)
//   PUBLIC_SITE_URL     the website's own address, e.g. https://www.example.com               (required on Render)
//   CONTACT_EMAIL       shown on the legal pages (optional)
//   GOOGLE_SITE_VERIFICATION, BING_SITE_VERIFICATION   search-engine ownership tokens (optional)
import { writeFileSync } from 'node:fs';

const env = process.env;
const onHost = Boolean(env['RENDER'] || env['CI']);
const apiUrl = (env['PUBLIC_API_URL'] ?? '').replace(/\/$/, '');
const siteUrl = (env['PUBLIC_SITE_URL'] ?? '').replace(/\/$/, '');

if (onHost && (!apiUrl || !siteUrl)) {
  console.error('PUBLIC_API_URL and PUBLIC_SITE_URL must be set for a hosted build (they are baked into the website).');
  process.exit(1);
}
for (const [name, value] of [['PUBLIC_API_URL', apiUrl], ['PUBLIC_SITE_URL', siteUrl]]) {
  if (value && !/^https?:\/\//.test(value)) {
    console.error(`${name} must start with https:// (got "${value}")`);
    process.exit(1);
  }
  if (value && onHost && !value.startsWith('https://')) {
    console.error(`${name} must be an https:// address on a hosted build`);
    process.exit(1);
  }
}
const q = (v) => JSON.stringify(v ?? '');
const file = `// GENERATED by scripts/write-env.mjs at build time. Do not edit; set the variables in the host instead.
export const environment = {
  apiUrl: ${q(apiUrl || 'http://localhost:4000/api')},
  countries: ['US'] as ('US' | 'IN')[],
  siteName: 'MacRequire',
  siteUrl: ${q(siteUrl || 'http://localhost:4200')},
  contactEmail: ${q(env['CONTACT_EMAIL'])},
  googleSiteVerification: ${q(env['GOOGLE_SITE_VERIFICATION'])},
  bingSiteVerification: ${q(env['BING_SITE_VERIFICATION'])},
};
`;
writeFileSync(new URL('../src/environments/environment.production.ts', import.meta.url), file);
console.log(`environment.production.ts written (api: ${apiUrl || 'localhost default'}, site: ${siteUrl || 'localhost default'})`);
